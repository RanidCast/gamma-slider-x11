def get_blackbody_rgb(temp):
    t = (int(temp) - 1000) // 100
    if t < 0:
        t = 0
    if t > 240:
        t = 240
    i = t * 3
    return BLACKBODY_COLOR[i], BLACKBODY_COLOR[i + 1], BLACKBODY_COLOR[i + 2]


def get_rgb_classic(temp):
    return get_blackbody_rgb(temp)


def get_rgb_aggressive(temp):
    r, g, b = get_blackbody_rgb(temp)
    if temp < 3200:
        t = (3200 - temp) / 2200.0
        red_boost = 1.0 + t * 0.85
        r = min(1.0, r * red_boost)
        g *= (1.0 - t * 0.55)
        b *= (1.0 - t * 0.82)
        if temp < 1800:
            extra = (1800 - temp) / 800.0
            b *= (1.0 - extra * 0.45)
            g *= (1.0 - extra * 0.15)
    return r, g, b


def get_rgb_mathematical(temp):
    T = float(temp)
    T_norm = 6500.0
    T_zero = 1000.0
    K0_G_LOW = -0.465
    K1_G_LOW = 0.098
    K0_B_LOW = -0.295
    K1_B_LOW = 0.082
    K0_R_HIGH = -0.380
    K1_R_HIGH = 0.080
    K0_G_HIGH = -0.480
    K1_G_HIGH = 0.095
    if T < T_norm:
        r = 1.0
        if T > T_zero:
            lg = math.log(T - T_zero)
            g = min(1.0, max(0.0, K0_G_LOW + K1_G_LOW * lg))
            b = min(1.0, max(0.0, K0_B_LOW + K1_B_LOW * lg))
        else:
            g = 0.0
            b = 0.0
    else:
        lg = math.log(T - (T_norm - T_zero))
        r = min(1.0, max(0.0, K0_R_HIGH + K1_R_HIGH * lg))
        g = min(1.0, max(0.0, K0_G_HIGH + K1_G_HIGH * lg))
        b = 1.0
    return r, g, b


def get_rgb_for_mode(temp, mode):
    if mode == MODE_AGGRESSIVE:
        return get_rgb_aggressive(temp)
    if mode == MODE_MATHEMATICAL:
        return get_rgb_mathematical(temp)
    return get_rgb_classic(temp)


def _ramp_value(val, rgb, brightness, gamma):
    return int(65535.0 * pow(val * rgb * brightness, 1.0 / gamma))


def build_ramp(temp, gamma, brightness=1.0, mode=MODE_CLASSIC, ramp_size=256):
    rgb = get_rgb_for_mode(temp, mode)
    r = []
    g = []
    b = []
    last = ramp_size - 1
    for i in range(ramp_size):
        val = i / last
        r.append(_ramp_value(val, rgb[0], brightness, gamma))
        g.append(_ramp_value(val, rgb[1], brightness, gamma))
        b.append(_ramp_value(val, rgb[2], brightness, gamma))
    return r, g, b


def identity_ramp(ramp_size=256):
    return [i << 8 for i in range(ramp_size)]


def clip_ramp_endpoints(r, g, b):
    def _scale(channel):
        n = len(channel)
        lo = channel[0]
        hi = channel[-1]
        if hi <= lo:
            return [int(i * 65535 / (n - 1)) for i in range(n)]
        out = []
        span = hi - lo
        for v in channel:
            scaled = int(round((v - lo) * 65535 / span))
            if scaled < 0:
                scaled = 0
            elif scaled > 65535:
                scaled = 65535
            out.append(scaled)
        out[0] = 0
        out[-1] = 65535
        return out
    return _scale(r), _scale(g), _scale(b)
